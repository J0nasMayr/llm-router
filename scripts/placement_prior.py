"""Prior demand for the allocation controller's first plan.

For each of the 2,500 queries GreenServ profiled offline (table
pregenerated_results in db/llm_db_backup.sql.gz), computes the reward of
every model as the live system does (alpha = beta = 0.5; accuracy and energy
per token normalized with config/metrics.yaml) and counts which model gives
the highest reward. The share of queries each model wins is written to
config/placement_prior.yaml.

Run from the repository root: ./venv/bin/python -m scripts.placement_prior
"""

import gzip
from collections import defaultdict
from pathlib import Path

import yaml

from src.metrics.energy import EnergyMetrics
from src.metrics.normalizer import MetricNormalizer

DUMP = Path("db/llm_db_backup.sql.gz")
OUTPUT = Path("config/placement_prior.yaml")
# Model ids in GreenServ's database that differ from config/models.yaml.
ID_MAP = {"phi-4-mini-4b": "phi-4-mini", "phi-4-14b": "phi-4"}
ALPHA = BETA = 0.5


def read_tables(path, tables):
    """Rows of the dump's COPY blocks for `tables`, as dicts per row. The dump
    uses PostgreSQL's text format: tab-separated values, \\N for NULL."""
    rows = {table: [] for table in tables}
    current, columns = None, None
    with gzip.open(path, "rt", encoding="utf-8") as dump:
        for line in dump:
            if current is None:
                if line.startswith("COPY public."):
                    name = line[len("COPY public.") :].split(" ", 1)[0]
                    if name in tables:
                        current = name
                        names = line[line.index("(") + 1 : line.index(")")]
                        columns = [c.strip().strip('"') for c in names.split(",")]
                continue
            if line.startswith("\\."):
                current = None
                continue
            values = line.rstrip("\n").split("\t")
            rows[current].append(
                {c: (None if v == "\\N" else v) for c, v in zip(columns, values)}
            )
    return rows


def model_shares(results, queries, model_ids, alpha=ALPHA, beta=BETA):
    """Share of queries for which each model in `model_ids` gives the highest
    reward. A query with several best models counts equally for each."""
    dataset_of = {q["query_id"]: q["dataset"] for q in queries}
    normalizer = MetricNormalizer()
    energy = EnergyMetrics()
    rewards = defaultdict(dict)
    for r in results:
        model = ID_MAP.get(r["model_id"], r["model_id"])
        if model not in model_ids:
            continue
        dataset = dataset_of.get(r["query_id"])
        energy_per_token = energy.calculate_per_token(
            float(r["energy_consumption"] or 0.0),
            int(r["input_tokens"] or 0),
            int(r["output_tokens"] or 0),
        )
        accuracy = normalizer.normalize("accuracy", float(r["accuracy"] or 0.0), dataset)
        efficiency = 1 - normalizer.normalize("energy_per_token", energy_per_token, dataset)
        rewards[r["query_id"]][model] = alpha * accuracy + beta * efficiency
    wins = defaultdict(float)
    for per_model in rewards.values():
        best = max(per_model.values())
        winners = [m for m, value in per_model.items() if value == best]
        for m in winners:
            wins[m] += 1.0 / len(winners)
    total = sum(wins.values()) or 1.0
    return {m: wins.get(m, 0.0) / total for m in model_ids}


def main():
    with open("config/models.yaml") as f:
        model_ids = set(yaml.safe_load(f))
    tables = read_tables(DUMP, {"pregenerated_results", "queries"})
    shares = model_shares(tables["pregenerated_results"], tables["queries"], model_ids)
    ordered = dict(sorted(shares.items(), key=lambda item: -item[1]))
    with open(OUTPUT, "w") as f:
        f.write(
            "# Share of GreenServ's 2,500 profiled queries for which each model\n"
            "# gives the highest reward (alpha = beta = 0.5). Prior demand for the\n"
            "# allocation controller's first plan. Generated by\n"
            "# scripts/placement_prior.py; do not edit by hand.\n"
        )
        yaml.safe_dump(
            {"placement_prior": {m: round(s, 4) for m, s in ordered.items()}},
            f,
            sort_keys=False,
        )
    for m, s in ordered.items():
        print(f"{m:15s} {s:.3f}")


if __name__ == "__main__":
    main()
